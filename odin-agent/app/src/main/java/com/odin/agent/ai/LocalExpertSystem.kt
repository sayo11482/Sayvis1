            lower.contains("btc") || lower.contains("بیت") || lower.contains("crypto") -> analyzeCrypto(prompt)
            lower.contains("eur") || lower.contains("gbp") || lower.contains("فارکس") || lower.contains("forex") -> analyzeForex(prompt)
