            lower.contains("تتر") || lower.contains("usdt") || lower.contains("تومان") || lower.contains("irr") -> analyzeTether(prompt)
            lower.contains("استراتژی") || lower.contains("strategy") || lower.contains("lit") || lower.contains("trend") -> analyzeStrategy(prompt)
            lower.contains("ریسک") || lower.contains("risk") || lower.contains("سرمایه") || lower.contains("capital") -> analyzeRisk(prompt)
            lower.contains("اسپرد") || lower.contains("spread") -> analyzeSpread(prompt)
            lower.contains("ویتاورس") || lower.contains("vittaverse") || lower.contains("بروکر") -> analyzeVittaverse(prompt)
            lower.contains("سلام") || lower.contains("hello") || lower.contains("help") || lower.contains("راهنما") -> welcomeMessage()
            else -> generalAnalysis(prompt)
        }
    }

